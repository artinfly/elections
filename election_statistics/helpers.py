def _text(value: Any) -> str:
    """
    Приводит значение ячейки Excel к строке.

    Описание:
        Excel часто хранит табельные номера и номера участков как числа (float).
        Функция проверяет: если дробная часть равна нулю, число конвертируется в int,
        чтобы избежать значений вроде "12345.0" в базе данных.
        Также удаляет лишние пробелы по краям.

    Аргументы:
        value: сырое значение ячейки.

    Возвращает:
        str: очищенная строка. None превращается в пустую строку.
    """
    if value is None:
        return ""
    if isinstance(value, float) and value.is_integer():
        return str(int(value))
    return str(value).strip()


def _date(value: Any) -> Optional[date]:
    """
    Разбирает дату из ячейки Excel.

    Описание:
        Поддерживает нативные объекты datetime/date, а также строки
        в форматах "дд.мм.гггг" и "гггг-мм-дд". Если строка содержит время,
        берется только первая часть (до пробела).

    Аргументы:
        value: сырое значение ячейки.

    Возвращает:
        date: объект даты или None, если разобрать не удалось.
    """
    # Если это уже объект datetime, извлекаем из него дату.
    if isinstance(value, datetime):
        return value.date()
    # Если это уже объект date, возвращаем как есть.
    if hasattr(value, "year"):
        return value

    # Пытаемся распарсить строку.
    head = _text(value).split()
    if not head:
        return None

    # Перебираем возможные форматы даты.
    for fmt in ("%d.%m.%Y", "%Y-%m-%d"):
        try:
            return datetime.strptime(head[0], fmt).date()
        except ValueError:
            continue
    return None


@contextmanager
def _sheet(upload: Any) -> Iterator:
    """
    Контекст-менеджер для безопасного чтения Excel-файлов.

    Описание:
        Открывает книгу в оптимизированном режиме (read_only), что критично
        для больших файлов. Гарантированно закрывает ресурсы (освобождает память)
        даже если внутри блока with произойдет исключение.

    Аргументы:
        upload: загруженный файл или байтовый поток с xlsx.

    Возвращает:
        Iterator: итератор строк активного листа (только значения, без стилей).

    Исключения:
        ValueError: если файл поврежден или не является xlsx.
    """
    try:
        book = openpyxl.load_workbook(upload, read_only=True, data_only=True)
    except Exception as exc:
        # Пользователю отдаем понятное сообщение, настоящую причину логируем в traceback.
        raise ValueError(BAD_FORMAT) from exc

    rows = book.active.iter_rows(values_only=True)
    try:
        yield rows
    finally:
        # Гарантированное закрытие файла.
        rows.close()
        book.close()


def _header(rows: Iterator, wanted: dict) -> dict:
    """
    Ищет строку с заголовками таблицы в Excel.

    Описание:
        Перебирает строки файла до тех пор, пока не найдет ту, где есть
        хотя бы одно совпадение с ожидаемыми заголовками. Поиск регистронезависимый.
        Это позволяет корректно читать файлы, где заголовок находится не в первой строке.

    Аргументы:
        rows: итератор строк листа.
        wanted: словарь ожидаемых заголовков (например, COLUMNS).

    Возвращает:
        dict: словарь вида {имя_колонки: индекс_в_строке}.

    Исключения:
        ValueError: если ни одна строка не похожа на заголовок.
    """
    # Создаем словарь для быстрого поиска без учета регистра.
    lookup = {name.casefold(): name for name in wanted}
    for row in rows:
        found = {}
        for index, cell in enumerate(row):
            key = _text(cell).casefold()
            if key in lookup:
                found[lookup[key]] = index
        # Если нашли хотя бы одну колонку, считаем строку заголовком.
        if found:
            return found
    raise ValueError(BAD_FORMAT)


def _by_number(value: Any) -> tuple:
    """
    Формирует ключ для умной сортировки списков.

    Описание:
        Обеспечивает правильный порядок: сначала идут числовые значения (1, 2, 10),
        отсортированные математически, а затем строковые значения по алфавиту.
        Без этого "10" стояло бы перед "2" при стандартной строковой сортировке.

    Аргументы:
        value: номер цеха или УИКа.

    Возвращает:
        tuple: кортеж приоритетов для функции sorted().
    """
    name = (value or "").strip()
    # 0 для чисел (пойдут первыми), 1 для строк.
    return (0, int(name), "") if name.isdigit() else (1, 0, name)


def padded_number(value: Any) -> str:
    """
    Дополняет числовой номер нулями слева до 3 знаков.

    Описание:
        Используется для формирования имен файлов и сортировки, чтобы
        цех "7" превратился в "007" и встал в правильное место в списке.

    Аргументы:
        value: номер (строка или число).

    Возвращает:
        str: дополненный номер ("7" -> "007"). Нечисловые значения не меняются.
    """
    name = (value or "").strip()
    return f"{int(name):03d}" if name.isdigit() else name


def department_file_name(department: str) -> str:
    """
    Формирует безопасное имя файла отчёта по номеру цеха.

    Описание:
        Приводит номер к трехзначному виду и заменяет запрещенные в файловых
        системах символы (например, слэши) на дефисы.

    Аргументы:
        department: номер цеха.

    Возвращает:
        str: безопасная строка для использования в качестве имени файла.
    """
    return BAD_NAME_CHARS.sub("-", padded_number(department))


def _apply_border(sheet: Any) -> None:
    """
    Применяет тонкую чёрную рамку ко всем заполненным ячейкам листа.

    Описание:
        Визуально оформляет границы таблиц в генерируемых Excel-отчетах.
        Проходит по всем использованным строкам и колонкам.

    Аргументы:
        sheet: объект листа openpyxl.
    """
    thin = Side(style="thin", color="000000")
    border = Border(left=thin, right=thin, top=thin, bottom=thin)
    for row_cells in sheet.iter_rows(
        min_row=1, max_row=sheet.max_row, min_col=1, max_col=sheet.max_column
    ):
        for cell in row_cells:
            cell.border = border


def _format_with_percent(count: int, total: int) -> str:
    """
    Форматирует число с добавлением процента от общего количества.

    Описание:
        Используется в строках "ИТОГО" сводных таблиц для наглядности.
        Процент округляется до целого числа.

    Аргументы:
        count: текущее количество.
        total: общее количество (если 0, процент не добавляется во избежание деления на ноль).

    Возвращает:
        str: строка вида "5 (50%)" или просто "5".
    """
    if not total:
        return str(count)
    return f"{count} ({round(count / total * 100)}%)"
